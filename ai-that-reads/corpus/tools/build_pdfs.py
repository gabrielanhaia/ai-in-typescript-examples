def _load_font(size: int):
    """A scalable font, without depending on any particular system font file."""
    candidates = [
        "/System/Library/Fonts/Supplemental/Courier New.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).exists():
            try:
                return ImageFont.truetype(candidate, size)
            except OSError:
                pass
    # Pillow 10.1+ ships a scalable fallback.
    return ImageFont.load_default(size=size)


def build_scanned() -> Path:
    """Render the price list to a raster image and embed it with no text layer.

    This is the only place in the corpus where these prices exist inside a
    document. A text extractor returns an empty string for this file, and every
    question in questions.jsonl marked ``requires_ocr`` is unanswerable until an
    OCR step is added to the pipeline. That is the point of the file.
    """
    path = OUT_DIR / "workshop-price-list-2026.pdf"
    png_path = OUT_DIR / "workshop-price-list-2026.page1.png"

    scale = 2  # ~144 dpi against A4
    w, h = int(595 * scale), int(842 * scale)
    img = Image.new("L", (w, h), 244)
    draw = ImageDraw.Draw(img)

    f_title = _load_font(int(19 * scale))
    f_head = _load_font(int(13 * scale))
    f_row = _load_font(int(11 * scale))
    f_note = _load_font(int(9 * scale))

    left = int(60 * scale)
    right = w - int(60 * scale)
    y = int(70 * scale)

    for kind, text in PRICE_LIST_LINES:
        if kind == "gap":
            y += int(12 * scale)
            continue
        if kind == "title":
            draw.text((left, y), text, font=f_title, fill=25)
            y += int(26 * scale)
        elif kind == "head":
            draw.text((left, y), text, font=f_head, fill=30)
            y += int(6 * scale)
            draw.line([(left, y + int(9 * scale)), (right, y + int(9 * scale))], fill=90, width=max(1, scale // 2))
            y += int(20 * scale)
        elif kind == "row":
            label, price = text.split("|")
            draw.text((left, y), label, font=f_row, fill=35)
            price_text = f"GBP {price}"
            bbox = draw.textbbox((0, 0), price_text, font=f_row)
            draw.text((right - (bbox[2] - bbox[0]), y), price_text, font=f_row, fill=35)
            y += int(17 * scale)
        elif kind == "note":
            draw.text((left, y), text, font=f_note, fill=60)
            y += int(13 * scale)

    # Make it look photocopied: seeded noise, a slight skew, and a dirty edge.
    rng = random.Random(20260201)
    pixels = img.load()
    for _ in range(w * h // 260):
        x = rng.randrange(w)
        yy = rng.randrange(h)
        pixels[x, yy] = max(0, pixels[x, yy] - rng.randrange(30, 150))
    img = img.rotate(0.45, resample=Image.BICUBIC, fillcolor=244, expand=False)
    edge = ImageDraw.Draw(img)
    edge.rectangle([0, 0, w - 1, h - 1], outline=190, width=max(2, scale))
    img = img.convert("L")
    img.save(png_path, optimize=True)

    c = pdfcanvas.Canvas(str(path), pagesize=A4)
    c.setTitle("Braxby Cycles workshop price list 2026 (scanned)")
    c.setAuthor("Braxby Cycles Ltd")
    c.setSubject("Workshop price list, scanned from paper")
    # No drawString anywhere on this page. The image is the whole page.
    c.drawImage(str(png_path), 0, 0, width=PAGE_W, height=PAGE_H)
    c.showPage()
    c.save()
    png_path.unlink()
    return path


