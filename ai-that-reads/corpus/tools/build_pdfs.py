#!/usr/bin/env python3
"""Build the PDF half of the Braxby Cycles sample corpus.

Every PDF in ``corpus/pdf/`` is generated by this script. The PDFs are
committed, so you do not need to run this to use the corpus — but the source of
every word in them is here, which matters for one file in particular: the
workshop price list is a page of pixels with no text layer, and this script is
the only place its content exists as text.

Three of the seven files are deliberately hostile to text extraction. They are
not badly made by accident:

* ``catalogue-2026-brakes-spread.pdf`` writes its two columns one *row* at a
  time, left cell then right cell, so any extractor that reads in content-stream
  order or sorts by (y, x) interleaves the two columns into nonsense.
* ``compatibility-2026.pdf`` draws a table cell by cell with no delimiters, so
  the extracted text loses every column boundary.
* ``workshop-price-list-2026.pdf`` renders its text to a raster image and embeds
  that, with no text drawn on the page at all. A text extractor returns nothing.

The remaining four are ordinary, well-behaved single-column documents, so that
the corpus is not uniformly awkward.

Output is byte-stable: ``rl_config.invariant`` fixes the PDF creation date and
document ID, and the raster page is generated from a seeded RNG. Re-running this
script on an unchanged source produces identical files.

Requirements: reportlab and Pillow.

    python3 -m venv .venv
    .venv/bin/pip install reportlab pillow
    .venv/bin/python corpus/tools/build_pdfs.py
"""

