# Trap 1: the two-column page written one row at a time
# --------------------------------------------------------------------------


def wrap(text: str, font: str, size: float, width: float) -> list[str]:
    """Greedy word wrap against real glyph widths."""
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if pdfmetrics.stringWidth(candidate, font, size) <= width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def build_two_column() -> Path:
    """A two-column page whose content stream runs across the columns.

    Each visual line is emitted as: left-column cell, then right-column cell, at
    the same y. Every extractor we know of — whether it reads the content stream
    in order or sorts text runs by (y, x) — therefore returns the two columns
    interleaved. That is the failure chapter 3 shows.
    """
    path = OUT_DIR / "catalogue-2026-brakes-spread.pdf"
    c = pdfcanvas.Canvas(str(path), pagesize=A4)
    c.setTitle("Braxby Cycles 2026 range guide - brakes")
    c.setAuthor("Braxby Cycles Ltd")
    c.setSubject("Range guide extract, brakes")

    col_w = (PAGE_W - 2 * MARGIN - 10 * mm) / 2
    left_x = MARGIN
    right_x = MARGIN + col_w + 10 * mm

    # Page furniture, drawn first and normally.
    c.setFont("Helvetica-Bold", 15)
    c.drawString(MARGIN, PAGE_H - MARGIN, "2026 range guide")
    c.setFont("Helvetica", 11)
    c.drawString(MARGIN, PAGE_H - MARGIN - 16, "Brakes - hydraulic disc calipers")
    c.setLineWidth(0.6)
    c.line(MARGIN, PAGE_H - MARGIN - 24, PAGE_W - MARGIN, PAGE_H - MARGIN - 24)

    left_heading = "Halvard R4 four-piston caliper"
    right_heading = "Halvard R2 two-piston caliper"

    left_text = (
        "The R4 is the four-piston caliper in the Halvard range and the one to "
        "fit if you are heavy on the brakes, ride loaded, or spend descents "
        "dragging a lever. Against the two-piston R2 it gives more pad area and "
        "a longer service life, at the cost of weight and a slightly firmer "
        "initial bite. The body is a two-piece forging with a bridge across the "
        "pistons, which is what keeps the flex out of it under load. Pistons are "
        "phenolic rather than alloy, so less heat is carried into the fluid on a "
        "long descent. The R4 is supplied with sintered pads as standard. "
        "Sintered pads take longer to bed in, are noisier in the wet for the "
        "first few rides, and last roughly twice as long as organic. Mount is "
        "post mount, front or rear, and the caliper takes the Halvard "
        "four-piston pad shape. Fitting a larger rotor than the frame mount is "
        "cut for needs the correct adapter for the position, and front and rear "
        "adapters are not interchangeable. Hose fitting is the current Halvard "
        "standard. It is not compatible with the 2019 R2 body without a new "
        "olive and insert, which is the single most common cause of a leak that "
        "appears a week after the job."
    )
    right_text = (
        "The R2 is the two-piston caliper and it is the right choice for most "
        "road bikes, most commuters, and any rider who is not routinely braking "
        "from speed with luggage on. It is lighter than the R4, it has a lighter "
        "lever feel, and it costs less to run because the pads are smaller. The "
        "body is a single-piece forging. Pistons are phenolic and the same fluid "
        "is used across the range, so a workshop only ever stocks one bleed kit. "
        "The R2 is supplied with organic pads as standard. Organic pads bed in "
        "within a few stops, are quieter, and wear faster, which is a trade most "
        "road riders take without noticing they have taken it. Mount is post "
        "mount, front or rear. The 2019 R2 body used a different hose fitting "
        "and is now superseded; a 2019 caliper being replaced needs a new olive "
        "and insert rather than a straight swap of the caliper. Adapters for the "
        "R2 have their own part numbers and several of them have been superseded "
        "in favour of the universal adapter, which ships with both bolt lengths "
        "rather than one."
    )

    font, size, leading = "Helvetica", 9.2, 12.4
    left_lines = wrap(left_text, font, size, col_w)
    right_lines = wrap(right_text, font, size, col_w)

    y = PAGE_H - MARGIN - 44

    # Headings, also emitted row-major: left heading then right heading.
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(left_x, y, left_heading)
    c.drawString(right_x, y, right_heading)
    y -= 16

    c.setFont(font, size)
    for i in range(max(len(left_lines), len(right_lines))):
        if i < len(left_lines):
            c.drawString(left_x, y, left_lines[i])
        if i < len(right_lines):
            c.drawString(right_x, y, right_lines[i])
        y -= leading

    c.setFont("Helvetica-Oblique", 8)
    c.drawString(
        MARGIN,
        18 * mm,
        "Braxby Cycles Ltd - 2026 range guide - prices on the product page",
    )
    c.drawRightString(PAGE_W - MARGIN, 18 * mm, "Page 14")
    c.showPage()
    c.save()
    return path


