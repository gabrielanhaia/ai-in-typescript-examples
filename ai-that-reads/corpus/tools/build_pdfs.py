def _footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Times-Roman", 8)
    canvas.drawString(MARGIN, 12 * mm, doc.footer_left)
    canvas.drawRightString(PAGE_W - MARGIN, 12 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_flowing(filename: str, title: str, footer_left: str, blocks) -> Path:
    """Write a normal single-column PDF from (style, text) blocks."""
    path = OUT_DIR / filename
    doc = BaseDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
        topMargin=MARGIN,
        bottomMargin=MARGIN,
        title=title,
        author="Braxby Cycles Ltd",
        subject=title,
        creator="Braxby Cycles document system",
    )
    doc.footer_left = footer_left
    frame = Frame(
        MARGIN,
        MARGIN,
        PAGE_W - 2 * MARGIN,
        PAGE_H - 2 * MARGIN,
        id="body",
        showBoundary=0,
    )
    doc.addPageTemplates([PageTemplate(id="all", frames=[frame], onPage=_footer)])
    story = []
    for style, text in blocks:
        if style is None:
            story.append(Spacer(1, text))
        else:
            story.append(Paragraph(text, style))
    doc.build(story)
    return path


